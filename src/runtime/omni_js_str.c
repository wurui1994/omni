static bool in_rng(const omni_cp_rng *t, size_t n, uint32_t cp) {
  for (size_t i = 0; i < n; i++) if (cp >= t[i].a && cp <= t[i].b) return true;
  return false;
}
#define IN_CASEDP(cp) in_rng(CASEDP, sizeof(CASEDP) / sizeof(CASEDP[0]), (cp))
#define IN_CIGN(cp) in_rng(CIGN, sizeof(CIGN) / sizeof(CIGN[0]), (cp))
/* 一对一那张表：按段线性找（段数三位数，而且只在非 ASCII 那条路上走） */
static bool case_one(bool up, uint32_t cp, uint32_t *out) {
  size_t n = up ? sizeof(CASE_UP) / sizeof(CASE_UP[0]) : sizeof(CASE_LO) / sizeof(CASE_LO[0]);
  for (size_t i = 0; i < n; i++) {
    uint32_t a = up ? CASE_UP[i].a : CASE_LO[i].a;
    uint16_t c = up ? CASE_UP[i].n : CASE_LO[i].n;
    uint8_t st = up ? CASE_UP[i].st : CASE_LO[i].st;
    int32_t d = up ? CASE_UP[i].d : CASE_LO[i].d;
    uint32_t off;
    if (cp < a) continue;
    off = cp - a;
    if (off - (off / st) * st != 0 || off / st >= (uint32_t)c) continue;
    *out = (uint32_t)((int64_t)cp + d);
    return true;
  }
  return false;
}
static const uint32_t *case_many(bool up, uint32_t cp, uint8_t *n) {
  size_t k = up ? sizeof(CASE_UPM) / sizeof(CASE_UPM[0]) : sizeof(CASE_LOM) / sizeof(CASE_LOM[0]);
  for (size_t i = 0; i < k; i++) {
    uint32_t c = up ? CASE_UPM[i].cp : CASE_LOM[i].cp;
    if (c != cp) continue;
    *n = up ? CASE_UPM[i].n : CASE_LOM[i].n;
    return up ? CASE_UPM[i].u : CASE_LOM[i].u;
  }
  return NULL;
}
/* 折一遍。ASCII 那条快路单独走（编译器自己只用 ASCII，这一族在热路径上）：等长、一次扫完。
   非 ASCII 那条路先摊成码点表（Final_Sigma 要往前后各看一眼），再一格一格拼 ——
   ss 这种一对多会让串变长，所以不能沿用等长那条路。 */
static omni_s16 js_case_map(omni_s16 v, bool up) {
  int64_t i, n = 0;
  bool ascii = true;
  uint32_t *cps;
  omni_s16 out;
  for (i = 0; i < v.len; i++) if (v.p[i] > 0x7f) { ascii = false; break; }
  if (ascii) return up ? omni_s16_upper(v) : omni_s16_lower(v);
  cps = (uint32_t *)omni_alloc((size_t)v.len * sizeof(uint32_t));
  for (i = 0; i < v.len; i++) {
    uint32_t cp = v.p[i];
    if (cp >= 0xD800 && cp <= 0xDBFF && i + 1 < v.len
        && v.p[i + 1] >= 0xDC00 && v.p[i + 1] <= 0xDFFF) {
      cp = 0x10000 + ((cp - 0xD800) << 10) + (v.p[i + 1] - 0xDC00);
      i++;
    }
    cps[n++] = cp;
  }
  out = omni_s16_of_utf8(omni_str_new("", 0));
  for (i = 0; i < n; i++) {
    uint32_t cp = cps[i];
    uint32_t one;
    uint8_t mn = 0;
    const uint32_t *mu;
    if (cp < 0x80) {
      uint32_t a = up ? ((cp >= 'a' && cp <= 'z') ? cp - 32 : cp)
                      : ((cp >= 'A' && cp <= 'Z') ? cp + 32 : cp);
      out = omni_s16_cat(out, omni_s16_of_code_point((int64_t)a));
      continue;
    }
    if (!up && cp == 0x3a3) {
      int64_t j2 = i - 1;
      while (j2 >= 0 && IN_CIGN(cps[j2])) j2--;
      if (j2 >= 0 && IN_CASEDP(cps[j2])) {
        int64_t k2 = i + 1;
        while (k2 < n && IN_CIGN(cps[k2])) k2++;
        if (k2 >= n || !IN_CASEDP(cps[k2])) {
          out = omni_s16_cat(out, omni_s16_of_code_point(0x3c2));
          continue;
        }
      }
    }
    mu = case_many(up, cp, &mn);
    if (mu != NULL) {
      uint8_t q;
      for (q = 0; q < mn; q++) out = omni_s16_cat(out, omni_s16_of_code_point((int64_t)mu[q]));
      continue;
    }
    out = omni_s16_cat(out, omni_s16_of_code_point((int64_t)(case_one(up, cp, &one) ? one : cp)));
  }
  return out;
}
omni_dyn omni_js_str_lower(omni_dyn s) {
  return omni_dyn_of_s16(js_case_map(want_s16(s), false));
}
omni_dyn omni_js_str_upper(omni_dyn s) {
  return omni_dyn_of_s16(js_case_map(want_s16(s), true));
}

