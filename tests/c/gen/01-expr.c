/* 第六刀第一片：整型表达式与优先级。
 * 每一格算完之后把结果收进一个 0..255 的和 —— 退出状态只有 8 位（wait(2) 的规矩），
 * 所以这一组的形状都是「算一堆、拼成一个字节」。任何一格算错，那个字节就变了。 */
int main(void) {
  int s = 0;

  /* 优先级：乘除模高于加减，加减高于移位，移位高于比较 */
  s += 1 + 2 * 3;                 /* 7  */
  s += (1 + 2) * 3;               /* 9  -> 16 */
  s += 20 / 3;                    /* 6  -> 22 */
  s += 20 % 3;                    /* 2  -> 24 */
  s += 1 + 2 << 1;                /* 6  -> 30：先加再移 */
  s += 1 << 2 | 1;                /* 5  -> 35：移位高于按位或 */
  s += (7 & 3) + (4 | 1) + (5 ^ 1); /* 3+5+4=12 -> 47 */

  /* 一元 */
  s += -(-3);                     /* 3  -> 50 */
  s += +4;                        /* 4  -> 54 */
  s += ~(-6);                     /* 5  -> 59 */
  s += !0;                        /* 1  -> 60 */
  s += !5;                        /* 0  -> 60 */

  /* 比较当整数用（C 规定是 0 或 1，不是别的真值） */
  s += (3 < 4) + (4 < 3) + (3 <= 3) + (3 > 4) + (4 >= 4) + (2 == 2) + (2 != 2);
                                  /* 1+0+1+0+1+1+0 = 4 -> 64 */

  /* 短路：右边有副作用才看得出来短没短 */
  int n = 0;
  int t = 0;
  t = (0 && (n = 1));             /* 不算右边 */
  s += t + n;                     /* 0 -> 64 */
  t = (1 || (n = 2));
  s += t + n;                     /* 1 -> 65 */
  t = (1 && (n = 3));
  s += t + n;                     /* 1+3 = 4 -> 69 */
  t = (0 || (n = 4));
  s += t + n;                     /* 1+4 = 5 -> 74 */

  /* `&&` 与 `||` 的结果一律 0/1，哪怕操作数是 7 */
  s += (7 && 9);                  /* 1 -> 75 */
  s += (7 || 9);                  /* 1 -> 76 */
  /* `a || b && c` 是 `a || (b && c)` */
  s += (0 || 1 && 0);             /* 0 -> 76 */
  s += (1 || 0 && 0);             /* 1 -> 77 */

  /* 三元，右结合 */
  s += 1 ? 2 : 3;                 /* 2 -> 79 */
  s += 0 ? 2 : 1 ? 5 : 6;         /* 5 -> 84 */

  /* 赋值是表达式，右结合；复合赋值 */
  int a;
  int b;
  a = b = 3;
  s += a + b;                     /* 6 -> 90 */
  a += 2; a -= 1; a *= 3; a /= 2; a %= 5;
  s += a;                         /* ((3+2-1)*3/2)%5 = 6%5 = 1 -> 91 */
  b = 1; b <<= 3; b >>= 1; b |= 1; b &= 7; b ^= 2;
  s += b;                         /* 1<<3=8 >>1=4 |1=5 &7=5 ^2=7 -> 98 */

  /* ++ 与 -- 的前后缀 */
  int i = 5;
  s += i++;                       /* 5 -> 103，i 变 6 */
  s += i;                         /* 6 -> 109 */
  s += ++i;                       /* 7 -> 116 */
  s += i--;                       /* 7 -> 123，i 变 6 */
  s += --i;                       /* 5 -> 128 */

  /* 逗号表达式：值是最后一个 */
  s += (1, 2, 3);                 /* 3 -> 131 */

  /* 32 位回绕：`int` 就是 32 位 */
  int big = 2147483647;
  big = big + 1;                  /* 回绕成 -2147483648 */
  s += (big < 0);                 /* 1 -> 132 */

  /* 括号里的强制转换（`(int)` 在 int 上是恒等，但要认得出来） */
  s += (int)7;                    /* 7 -> 139 */

  return s;
}
