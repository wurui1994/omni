/* 边界：语句标签长在 `switch` 里面。
 *
 * 第二十四片把 `goto` 收成「函数一台状态机 + 一条分派链」，每种语句各出一小段就能被
 * 重新进入。只有 switch 不够：case 那台分派与标签这台分派要在**同一串嵌套 BLOCK**
 * 上各插自己的段界，而且重新进入时还得跳过选择子的求值。两台分派交错是一件独立的事，
 * 所以这儿是我们的边界，不是错误 —— C 允许（标签的作用域是整个函数）。 */
int main(void) {
  int i = 0;
  switch (i) {
  case 0:
  again:
    i += 1;
    break;
  }
  if (i == 1) goto again;
  return i;
}
