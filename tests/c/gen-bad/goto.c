/* 边界：`goto` 跳到**不在外围块上**的标签。
 *
 * 第十片把带标签的块做成了一台状态机（`openLabels`），而分派只能把控制送到**那个块
 * 自己那一层**的标签上。`inner` 长在 for 的循环体里，从循环外面跳进去要先跳进那个块 ——
 * 结构化控制流下「跳进一个 block 的中间」根本没有写法，得先把两个块合成一台状态机
 * （relooper 那一路）。C 允许（标签的作用域是整个函数），所以这是我们的边界，不是错误。 */
int main(void) {
  int i;
  goto inner;
  for (i = 0; i < 3; i++) {
  inner:
    i += 10;
  }
  return i;
}
