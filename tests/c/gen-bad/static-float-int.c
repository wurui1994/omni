/* 整型的**静态**初始化式里的浮点常量还没到（`int n = 1.9;` 在 C 里是 1）。
 *
 * 常量表达式的求值器有两份：整型那一份是 BigInt 的（`constExpr`），浮点那一份是
 * number 的（`constFloatExpr`）。目标是整型而初始化式里有浮点时要的是「在浮点里算完
 * 再截尾」—— 那是把两份合流的一步，不是这一片。**自动**存储期的那一侧没有这个洞：
 * `int n = 1.9;` 在函数里走的是 `castTo`，早就通了。 */
static int n = 1.9;

int main(void) {
  return n;
}
