"""real_format.omni 的参照实现：Python 的 '%.6g' 就是 C 的 printf %.6g。"""

vs = [
    0.0, 1.0, -1.0, 0.5, -0.125, 2.5,
    1.0 / 3.0, 2.0 / 3.0, 1.0 / 7.0,
    99999.0, 100000.0, 999999.0, 1000000.0, 1000001.0,
    0.0001, 0.00001, 1.5e-5, 1.0e-20,
    123456789.0, 1.0e20, 1.0e21,
    3.14159265358979, 2.718281828459045,
    1e-4, 9.9999995e5, 0.000123456789,
]

for v in vs:
    print("%.6g" % v)

acc = 0.0
for v in vs:
    acc = acc + v
    print("%.6g" % acc)
print("%.6g" % (acc * 1.0e-10))
print("%.6g" % (acc / 3.0))
