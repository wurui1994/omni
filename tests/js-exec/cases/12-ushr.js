// `>>>`（与 `>>>=`）：**32 位、无符号**的右移。
//
// 它不属于 `>> << & | ^` 那一族 —— 那一族在这个值域里只对 bigint 成立（方言的 int
// 就是 int64），而 JS 的 `>>>` 是按 32 位定义的、对 BigInt 直接 TypeError。所以它降到
// i32 那三条 op 上（`u>>` 算规范形 int32、`tou` 把那些位当无符号读回来）。
//
// 取样点挑的都是"能分辨错法"的：
//   - 负数：`-1 >>> 0` 要 4294967295（不是 -1，也不是 2147483647）
//   - 超出 i32 的入参：`2147483648 >>> 0` 要按 2^32 取模，不是饱和到 2147483647
//     （C 腿一开始正是饱和的 —— `(int32_t)double` 在 C 里是未定义行为）
//   - 移位量：`>>> 32` 与 `>>> 0` 同（计数掩码 31），`>>> 33` 与 `>>> 1` 同
const cases = [
  [0, 0], [1, 0], [-1, 0], [-1, 1], [-1, 31], [-1, 32],
  [255, 4], [2147483648, 0], [4294967295, 0], [4294967295, 16],
  [-2147483648, 1], [123456789, 7], [-123456789, 7], [1, 31], [1, 32], [7, 33],
];
for (const c of cases) {
  console.log(`${c[0]} >>> ${c[1]} = ${c[0] >>> c[1]}`);
}
// 复合赋值那一格（`>>>=` 与 `>>>` 走同一条降级）
let z = -1;
z >>>= 4;
console.log(`compound ${z}`);
// 与有符号右移的对照：两个算符在这个值域里连**操作数类型**都不同 ——
// `>>` 要 bigint（int64），`>>>` 要 number（i32）。这与 JS 自己的规矩一致：
// `-16n >> 2n` 合法，而 `-16n >>> 2n` 在 JS 里就是 TypeError。
console.log(`signed ${-16n >> 2n} unsigned ${-16 >>> 2}`);
