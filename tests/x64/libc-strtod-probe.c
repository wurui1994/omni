/* `strtod` 的判据：**按位**与平台 libc 比。
 *
 * 打印那一头已经精确了（`decExpand`），这一份量的是反过来：一串十进制文字该落到哪个
 * double 上。判据是**位模式**（`%016llx`）而不是印出来的样子 —— 差一个 ulp 在十进制上
 * 常常看不见，在位上藏不住。
 *
 * 挑的串都是已知难点：`2.2250738585072011e-308`（glibc 2.16 之前在这儿死循环过）、
 * `1e23`（离两个 double 正好一样远的那一类）、`9007199254740993`（2^53 + 1）、
 * 一长串有效数字（要正确舍入就得看第 17 位之后）、以及溢出/下溢的边。
 *
 * 后一半是**往返**：一个 double 印成 `%.17g` 再读回来，位必须一模一样 ——
 * 这一条不依赖任何外部尺子，自己就能判自己。
 *
 * 跑法见 `tests/c/libc-strtod.js`。
 */
int printf(const char *, ...);
double strtod(const char *, char **);

typedef union { double d; unsigned long long u; } DU;

static const char *strs[] = {
  "0", "-0", "1", "0.5", "0.1", "0.2", "0.3", "1e23", "1e-23",
  "2.2250738585072011e-308",          /* glibc 那个著名的死循环样本 */
  "2.2250738585072014e-308",          /* 最小规格化 */
  "4.9406564584124654e-324",          /* 最小非规格化 */
  "9007199254740993",                 /* 2^53 + 1：落到偶数那边 */
  "9007199254740992.5",               /* 正好一半：半到偶 */
  "4503599627370497.5",
  "123456789012345678901234567890",
  "0.142857142857142857142857142857142857",
  "1.7976931348623157e308",           /* 最大 */
  "1.7976931348623159e308",           /* 溢出成 inf */
  "1e-400",                           /* 下溢成 0 */
  "3.141592653589793238462643383279502884197",
  "1e308", "1e-308", "1e100", "1e-100", "6.02214076e23", "1.602176634e-19",
  "0.30000000000000004", "2.5e-1", "  \t 42.125", "+7.75e+2",
};

static double vals[] = {
  0.1, 0.2, 0.3, 1.0 / 3.0, 2.0 / 3.0, 3.141592653589793, 2.718281828459045,
  1e-5, 1234.5678, 123456789.123456789, 1e16, 9007199254740993.0,
  4503599627370497.0, 1e100, 1e-100, 1e300, 1e-300,
  2.2250738585072014e-308, 5e-324, 1.7976931348623157e308, 6.02214076e23,
};

int main(void) {
  int n = (int)(sizeof(strs) / sizeof(strs[0]));
  for (int i = 0; i < n; i++) {
    DU u;
    u.d = strtod(strs[i], (char **)0);
    printf("%d %016llx  <- %s\n", i, u.u, strs[i]);
  }
  /* 往返：印 17 位再读回来，位必须相同。 */
  int m = (int)(sizeof(vals) / sizeof(vals[0]));
  int bad = 0;
  for (int i = 0; i < m; i++) {
    char buf[64];
    DU a, b;
    a.d = vals[i];
    /* 自己印自己读：`snprintf` 那一路与 printf 同一份代码。 */
    extern int snprintf(char *, unsigned long, const char *, ...);
    snprintf(buf, sizeof(buf), "%.17g", a.d);
    b.d = strtod(buf, (char **)0);
    if (a.u != b.u) { bad++; printf("往返 FAIL %s  %016llx -> %016llx\n", buf, a.u, b.u); }
  }
  printf("往返 %d 个，%d 个不同\n", m, bad);
  return bad == 0 ? 0 : 1;
}
