/* 浮点打印的判据：与平台 libc 逐行比。
 *
 * 这一格是自带 libc 里**唯一还差一位的地方**（第一百四十片记过：数字是「归一化 + 逐位
 * 取整」抠出来的，全在 double 上算，所以 `%.17g` 最后一两位可能差一个 ulp）。要还它得用
 * 大整数（dragon4 / Ryu 那一类），而「差多少」得先有个能反复量的数 —— 就是这一份。
 *
 * 挑的值都是**已知难点**：1/3 那种无限循环的、2^-1074 那种非规格化的、1e308 那种
 * `%f` 要印三百多位的、9007199254740993 那种正好过 2^53 的、以及 inf/nan 与 -0。
 *
 * 跑法：`node tests/c/libc-float.js`（本机 arm64 macOS：一份用 `cc` 编当尺子，
 * 一份用我们自己那台 C 前端 + `--libc self` 编，逐行比）。
 */
int printf(const char *, ...);

static double vals[] = {
  0.0, -0.0, 1.0, -1.0, 0.5, 0.1, 0.2, 0.3,
  1.0 / 3.0, 2.0 / 3.0, 3.141592653589793, 2.718281828459045,
  1e-5, 1234.5678, 123456789.123456789, 1e15, 1e16, 1e17,
  9007199254740993.0, 4503599627370497.0,
  1e100, 1e-100, 1e300, 1e-300,
  2.2250738585072014e-308, 5e-324, 1.7976931348623157e308,
  6.02214076e23, 1.602176634e-19, 0.30000000000000004,
};

int main(void) {
  int n = (int)(sizeof(vals) / sizeof(vals[0]));
  for (int i = 0; i < n; i++) {
    double x = vals[i];
    printf("%d %.17g\n", i, x);
    printf("%d %g\n", i, x);
    printf("%d %e\n", i, x);
    printf("%d %.15e\n", i, x);
    printf("%d %.3f\n", i, x);
  }
  /* `%f` 印大数：整数部分是三百多位，一位都不许差。 */
  printf("big %f\n", 1e100);
  printf("big %f\n", 1.7976931348623157e308);
  printf("small %f\n", 5e-324);
  printf("small %.20f\n", 0.1);
  /* 宽度与标志（这一格早就与 glibc 相同，一起看着） */
  printf("[%10.4f] [%-12.6g] [%+.2e]\n", 3.14159, 0.000123456, -42.5);
  return 0;
}
