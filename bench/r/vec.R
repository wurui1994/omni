# bench/r/vec.R —— 逐元素 + 回收：R 在这一格是 C 里的一趟循环（它最快的一档），
# 我们这边也是一趟编出来的循环。这是对 R 最有利的比法，所以它才该在尺子里。
#
# 印的是 `%% 999983` —— 尺子先比答案再比时间，而这个和有 1e13 那么大，七位有效数字印出来
# 是 `1.2e+13`：两条腿末位的一点差别会变成"答案不一样"。取个模，答案这一关就只判**算得对**。
# （"定点还是科学记数"那一格现在是照 `format.c` 抄的、与 R 逐字节一致 —— SPEC 第四节第 9 条。）
n <- 200000
xs <- 1:n
s <- 0
for (k in 1:100) s <- s + sum(xs * 2 + 1)
cat(s %% 999983, "\n")
