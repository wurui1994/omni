// **三格"声明那一句"上的洞** —— 都是真实 C/C++ 里到处都有、这条腿上却悄悄少做了的：
//
// 1. **一句里好几个声明符**（`int a = 1, b = 2;`）：它们在树上是**同一格** `init` 里的
//    好几格 `(d …)`。从前只取第一格 —— `b` 根本没声明（方言报"未声明的变量"）。
//    这是"覆盖还是追加"那个形状的又一次：**只取第一格**。
//
// 2. **多维数组**（`int m[2][3];`）：树上是套起来的 `array`，**外层那格带的是最后那一维**。
//    落成"列表的列表"：外层 `anew` 之后要现搭一段 `while` 把每一格填上一个内层 `anew` ——
//    不填的话那几格是 null，`m[0][0] = 1` 在运行期报 "null reference"。
//    从前连名字都读不出来（名字埋在两层声明符底下，`nameOf` 答 null）。
//
// 3. **函数里的 `static` 局部量**：`static` 当修饰丢掉之后它成了普通局部量、**每次进门
//    重新初始化** —— `counter()` 老答同一个数（**答案静默地错**，与 `static` 数据成员
//    那一格同一个形状）。落法也与那一格同一手：一格模块级的量（这个函数一份），
//    非零的初值摆在 `main` 体的最前面（方言的 `(global 名字 类型)` 按设计零初始化）。
//    初值要跑一段才算得出来的当场报 —— C++ 那边是"第一次走到才初始化"，伪造不出来。
//
// 钉住八件事：三个声明符各自成立、第二个声明符也能带初值、二维数组读写、二维数组按下标
// 循环填、带非零初值的 static 局部量留着、不带初值的 static 局部量从零起、两个函数各一份、
// 同名的普通局部量与别的函数里那格 static 互不相干。
#include <stdio.h>

int counter() {
  static int n = 10;
  n = n + 1;
  return n;
}

int zero() {
  static int n;
  n = n + 2;
  return n;
}

int main() {
  int a = 1, b = 2, c = a + b;
  printf("%d %d %d\n", a, b, c);
  int m[2][3];
  m[0][0] = 1;
  m[1][2] = 7;
  printf("%d %d\n", m[0][0], m[1][2]);
  int i = 0;
  int s = 0;
  while (i < 2) {
    int j = 0;
    while (j < 3) {
      m[i][j] = i * 10 + j;
      j = j + 1;
    }
    i = i + 1;
  }
  i = 0;
  while (i < 2) {
    int j = 0;
    while (j < 3) {
      s = s + m[i][j];
      j = j + 1;
    }
    i = i + 1;
  }
  printf("%d %d %d\n", m[1][1], m[0][2], s);
  /* 两次调用分开写 —— C++ 里同一句里几个实参的求值次序是不定的。 */
  int c1 = counter();
  int c2 = counter();
  printf("%d %d\n", c1, c2);
  int z1 = zero();
  int z2 = zero();
  printf("%d %d\n", z1, z2);
  /* 这个 `n` 是 main 自己的局部量，与那两个函数里的 static 各不相干。 */
  int n = 100;
  printf("%d %d\n", n, counter());
  return 0;
}
