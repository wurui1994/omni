// **四格"程序最外层与副作用"上的洞** —— 探针一趟撞出来的，四格都很常见：
//
// 1. **文件作用域的量**（`int g = 5;` / `const int K = 10;` / `int xs[3] = {…};`）从前整格
//    **丢掉**：读它的地方报"未声明的变量"。落法与 `static` 数据成员／`static` 局部量同一手：
//    发一格模块级的量，初值摆在 `main` 体的最前面（方言的 `(global 名字 类型)` 按设计
//    零初始化、不带初值）。这一趟要排在函数体之前，还要跳过三样不是"量"的东西：
//    函数声明（`int later(int);`）、`static` 成员的类外定义、`extern`。
//
// 2. **字符字面量**（`'A'` / `'\n'`）在 C++ 里就是一格整数（它的编码）—— 从前"这一格
//    表达式还没接"。转义走公共层那份 `cUnescape`（与格式串同一台机器）。
//
// 3. **`while (i--)`**：条件里那格 `i--` 是"要先跑几句再交一格值"（`block-expr`），
//    而公共层把那几句**提到循环之前** —— 于是自减只跑一趟、条件永远为真，程序**静默地
//    死循环**（比答错更难发现：三十秒后看门狗才把它停了）。现在条件里带副作用的那一档
//    改写成"永真循环 + 体最前面 `if (!条件) break`"：条件那几句每趟都在体里跑，而
//    `continue` 回到体的开头正好就是 C 里"重新判条件"。`for (;cond;)` 那一格同一手。
//
// 4. **类里写着的默认成员初值**（C++11 的 `int a = 7;`）从前整格丢掉：`D d;` 之后 `d.a`
//    是 0 而 `c++` 给 7（**答案静默地错**）。现在造对象时用它（`zeroField`）。
//
// 另外：**`sizeof` 有意不接**（当场报）—— 方言里没有内存布局这件事，整数也不是四个字节，
// 答一个 4 出来就是撒谎，而那个谎会顺着 `sizeof(xs)/sizeof(xs[0])` 传成错的长度。
//
// 钉住八件事：全局量读得到、改得动、`const` 全局、函数**先声明后定义**、默认成员初值、
// 字符字面量当整数用与 `%c` 印出来、`while (i--)` 不死循环且答案与 `c++` 相同、`<<=`。
#include <stdio.h>

int g = 5;
const int K = 10;

/* 先声明、后定义 —— 体在文件末尾（C 里最常见的排法）。 */
int later(int x);

struct D {
  int a = 7;
  int b;
};

int main() {
  printf("%d %d\n", g, K);
  g = g + 1;
  printf("%d\n", g);
  printf("%d\n", later(3));
  D d;
  /* 只印带默认初值的那一格 —— `d.b` 在 C++ 里是**没初始化**的（读它的值没有意义）。 */
  printf("%d\n", d.a);
  char c = 'A';
  c = c + 2;
  printf("%c %d\n", c, (int)'a');
  int i = 3;
  int n = 0;
  while (i--) {
    n = n + i;
  }
  printf("%d %d\n", i, n);
  int m = 1;
  m <<= 3;
  printf("%d\n", m);
  return 0;
}

int later(int x) {
  return x * 100;
}
