// 格式串：**几格转换挤一行**（走公共层那一份 —— 与 jancy 的 `printf` 同一张转换表）。
//
// 从前这一门只接"一格转换 + 末尾换行"，所以 `printf("a=%d b=%d\n", a, b)` 当场报。
// 现在格式那一层交给 `src/core/lower/fmt.js` 的 `fmtToIR`：切成字面量与转换，
// 每格转换落成一格现成的串内建（`tostr` / `sfix` / `ssci` / `sbase`），再用 `+` 串起来。
//
// 钉住二十二件事：两格转换、浮点的三种写法（`%.2f` / `%.3e` / `%g`）、`%s` 与 `%%`、
// 十六进制与八进制、纯文本一格转换都没有、转换挨着排（`%d%d%d`）、转换后面还有文字、
// 宽度与左右对齐、**补零时零排在负号后面**（`%05d` 印 -42 是 `-0042`，不是 `000-42`）、
// 浮点带宽度、`%.2s` 是"最多两个字符"、**末尾没有换行**（落成 `write`）、
// 一句里带两个换行（切成两段）、`+` 与空格标志、`#`（`0x` / 前导 0 / 小数点一定印）、
// 整数上的精度（`%.3d` 是"至少三位"）、以及**几格次序写反了看不出来的**：
// `%08.3d` 收 -5 是 `    -005`（一写精度 `0` 标志就作废）、`%.0d` 收 0 一个字符都不印、
// `%#x` / `%#o` 收 0 都不加前缀。最后是 `%c`（一个码位 -> 一个字符）与 `*` / `.*`
// （宽度、精度从实参来 —— **C 的实参次序是"宽度、精度、值"**，数错会把后头全错位；
// 宽度是负数等于左对齐 + 取绝对值）。
//
// 宽度那一层会把那一段**落成一格临时量**（`block-expr` + `let`）：它要读好几次，
// 直接抄几遍的话 `printf("%5d\n", f())` 会把 `f()` 多跑几趟。
#include <stdio.h>

int main() {
  int a = 1;
  int b = 22;
  printf("a=%d b=%d\n", a, b);
  double x = 3.14159;
  printf("%.2f | %.3e | %g\n", x, x, x);
  printf("%s=%d%%\n", "pct", 100);
  printf("hex %x oct %o\n", 255, 8);
  printf("no args\n");
  printf("%d%d%d\n", 1, 2, 3);
  printf("%d then text\n", 5);
  // 宽度与两个标志（右对齐 / 左对齐 / 补零 —— 补零时零排在负号**后面**）
  printf("[%5d][%-5d][%05d]\n", 42, 42, 42);
  printf("[%05d][%5d]\n", -42, -42);
  printf("[%8.2f][%-8.2f]\n", 3.14159, 3.14159);
  printf("[%6s][%-6s][%.2s]\n", "ab", "ab", "abcd");
  // 末尾**没有**换行（落成 write）、以及一句里带两个换行（切成两段）
  printf("A");
  printf("B%d", 1);
  printf("\n");
  printf("x=%d\ny=%d\n", 7, 8);
  // `+` / 空格 / `#` 三个标志，以及整数上的精度（`%.3d` 是"至少三位"）
  printf("[%+d][%+d][% d][% d]\n", 5, -5, 5, -5);
  printf("[%#x][%#X][%#x][%#o][%#o]\n", 255, 255, 0, 8, 0);
  printf("[%#.0f][%#g][%.3g]\n", 3.0, 1.5, 3.14159);
  printf("[%.3d][%.3d][%.0d][%08.3d]\n", 5, -5, 0, -5);
  printf("[%+08.2f][%+-8.2f]\n", 3.14159, 3.14159);
  // `%c` 是一个码位 -> 一个字符
  printf("[%c%c%c][%3c][%-3c]\n", 72, 105, 33, 65, 65);
  // `*` / `.*`：宽度与精度从实参来（C 的次序是宽度、精度、值；宽度是负数 = 左对齐）
  int w = 6;
  printf("[%*d][%*d][%-*d]\n", w, 42, -w, 42, w, 42);
  printf("[%.*f][%.*s][%*.*f]\n", 3, 3.14159, 2, "abcd", 9, 2, 3.14159);
  return 0;
}
