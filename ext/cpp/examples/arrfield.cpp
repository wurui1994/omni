// **数组字段 + 按值拷要连里头一起拷**（`int xs[3];`）。
//
// 两格洞一起补：
//   1. 从前 `int xs[3];` 当成员时 `nameOf` 读 `(array (n xs) (num 3))` 答 **null** ——
//      字段表里多出一格叫 `null` 的、`xs` 根本不存在（方言报"类 Bag 没有字段 xs"，
//      病因不在那儿）。现在收成一格列表字段，**长度也记下来**：造对象时照它开格子
//      （开 0 格的话 `xs[0] = 10` 就越界）。
//   2. 值语义那一刀里"记录带列表就当场报"的那一格接上了：拷的时候现搭一段
//      `anew` + `while` 把元素逐格拷过去（方言没有"拷一份列表"的内建）。
//      字典仍当场报 —— 方言里没有能装下键列表的类型，拷不了。
//
// 钉住四件事：字段的读写、长度（循环求和）、按值传进去改不到调用者的那一格、
// 以及拷贝初始化之后**两格列表互不相干**。
#include <stdio.h>

struct Bag {
  int n;
  int xs[3];
};

void fill(Bag b) {
  b.n = 99;
  b.xs[0] = 77;
}

int main() {
  Bag a;
  a.n = 1;
  a.xs[0] = 10;
  a.xs[1] = 20;
  a.xs[2] = 30;
  fill(a);
  printf("%d %d\n", a.n, a.xs[0]);
  int s = 0;
  for (int i = 0; i < 3; i++) {
    s = s + a.xs[i];
  }
  printf("%d\n", s);
  Bag c = a;
  c.xs[1] = 55;
  printf("%d %d\n", a.xs[1], c.xs[1]);
  return 0;
}
