# ext/python/examples/intdiv.py —— `//` 与 `%` 那一格：**整数上要精确、符号要跟着除数**
#
# python 的这两个算子与 C 不是一回事：
#   * `//` 是**向下取整**（`-7 // 2` 是 -4，C 的 `/` 给 -3）；
#   * `%` 的**符号跟着除数**（`-7 % 2` 是 1，C 的 `%` 给 -1）；
#   * 而且两个都必须**精确**：从前这两格落成 `floor(a/b)` 再取整，double 只有 53 位
#     有效位，于是 `4052555153018976267 // 3` 答 …992000（python 答 …992089）、
#     `4052555153018976267 % 3` 答 267（python 答 0）—— 三条腿一起静静答错。
#     现在整数那一档落成"截向零的商 / C 的余数 + 异号时修一格"，一步 double 都不碰。
#
# 这一份把四种符号组合 × 小数与大数都走一遍，外加 `divmod` 那两格与自增写法。


def main():
    # 一、四种符号组合（小数：这一档从前也是对的，别弄坏）
    for a in [7, -7]:
        for b in [2, -2]:
            print(a // b, a % b)
    print(0 // 3, 0 % 3, 0 // -3, 0 % -3)

    # 二、贴着 2^53 以上的大数：这一档从前每一格都错
    big = 4052555153018976267
    for b in [3, -3, 7, 1000000007]:
        print(big // b, big % b)
        print(-big // b, -big % b)

    # 三、整除的那一格（余数为零时不许修）
    print(big // 1, big % 1)
    print((big * 1) // big, big % big)
    print(-big // big, -big % big)

    # 四、写法上的两种：`x //= n` 与循环里反复取余
    x = big
    x //= 10
    print(x)
    n = big
    digits = 0
    while n > 0:
        digits = digits + n % 10
        n = n // 10
    print(digits)

    # 五、浮点那一档不受影响（`//` 出浮点、`%` 符号跟着除数）
    print(7.0 // 2, -7.0 // 2, 7.5 % 2, -7.5 % 2)


main()
