# ext/python/examples/floatrepr.py —— `str(float)` 的排版门槛
#
# python 的浮点转串有三条门槛，各自都能单独错：
#   1. 最短往返（`0.1` 不是 `0.1000000000000000055`）；
#   2. 整数值补 `.0`（`4.0` 不是 `4`）；
#   3. **定点当且仅当 `-4 < decpt <= 16`**（`1e15` 印 `1000000000000000.0`，
#      `1e16` 印 `1e+16`）。第三条是 `%g` 那一族最容易分叉的地方 —— 它的门槛跟着
#      有效位数走，于是 `1e15` 会被印成 `1e+15`。
#
# 这一份用循环把 10 的幂从 1e-320 一路扫到 1e308，每一档都印一遍 —— 门槛错一格就现形。


def main():
    # 10 的幂往上：前 17 档是定点、往后是指数
    x = 1.0
    for i in range(20):
        print(x)
        x = x * 10.0

    # 带一位小数的同一族（`2.5e15` 那一档）
    y = 2.5
    for i in range(20):
        print(y)
        y = y * 10.0

    # 10 的幂往下：`1e-05` 起转指数
    z = 1.0
    for i in range(12):
        print(z)
        z = z / 10.0

    # 最短往返那一族
    print(1.0 / 3.0, 2.0 / 3.0, 1.0 / 7.0)
    print(0.1 + 0.2, 0.1 * 3.0)
    print(1.0 / 0.0 if False else 2.0 ** 0.5)

    # 整数值、负号、零
    print(4.0, -4.0, 0.0, -0.0, 100.0, -0.5)

    # 17 位那一档（16 位定点、17 位指数）
    print(1234567890123456.0)
    print(12345678901234567.0)
    print(123456789012345678.0)

    # 极值
    print(1.7976931348623157e308, 5e-324, 2.2250738585072014e-308)


main()
