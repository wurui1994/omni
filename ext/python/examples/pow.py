# ext/python/examples/pow.py —— `**` 那一格：**整数次幂要精确**
#
# python 的 `a ** b` 有三档，各自都能单独错：
#   1. 两边都是整数、指数非负 -> **整数**，而且要精确到 64 位的最后一位；
#   2. 指数是负数 -> 浮点（`2 ** -1` 是 0.5）；
#   3. 有一边是浮点 -> 浮点。
#
# 第一档是这一份逼出来的那一格：从前我们走 `pow(double, double)` 再取整，而 double 只有
# 53 位有效位 —— `3 ** 39`（= 4052555153018976267）落在 int64 里却落不进 double，
# 于是**静静答错**（我们印 …256，python 印 …267）。现在那一档走方言的 `(ipow)`。
# 这里挑的数刻意都**贴着 2^53 与 2^63 之间**：小的那些谁都对，只有这一段照得出来。
#
# 溢出 64 位那一格（`2 ** 64`）不在这一份里 —— 它现在报"无上界的整数还没接"
# （python 答得出，我们答不出：那是借 `longobject.c` 那一刀的事）。


def main():
    # 一、字面量指数（静态那一条路：类型推得出 int）
    print(3 ** 39)
    print(7 ** 22)
    print(2 ** 62)
    print(10 ** 18)
    print(5 ** 27)
    print(6 ** 24)
    print(-3 ** 39)
    print((-3) ** 39)
    print((-2) ** 63)
    print(0 ** 0, 1 ** 0, 2 ** 0, 2 ** 1)

    # 二、指数在变量里（箱子那一条路：整数那一支在运行期问"指数非负吗"）
    b = 3
    e = 39
    print(b ** e)
    for i in range(10):
        print(2 ** (i * 6))

    # 三、负指数与浮点：这两档是 real
    n = -1
    print(2 ** n)
    print(2 ** -2)
    print(2 ** 0.5)
    print(2.0 ** 3)

    # 四、bool 当指数（bool 就是 int 的一种）
    print(2 ** True, 2 ** False)


main()
