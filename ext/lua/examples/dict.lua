-- ext/lua/examples/dict.lua —— 与 go / V / awk / nim 那四份 dict **同一件事**
--
-- 期望输出逐行相同：1 / 3 / 4 / yes。
-- lua 这一份是这一族里**最难判的一门**：lua 的 table 既是数组又是字典，
-- `local m = {}` 之后到底当哪种用，树上看不出来。所以这门语言的判据只能是
-- **"它被怎么用过"**：用串当过键（`m["a"]`）就算 map。判不了的形状（键是变量、
-- 既 `t[1]` 又 `t["a"]`）当场报错，不猜 —— 那两条写在 tograph.js 末尾的不足里。
--
-- 还有一格值得单看：lua 问"在不在"的写法是 `m["a"] ~= nil`，而图上**缺键是错误**
-- （`map-get` 会报）。这两条语义对不上，所以映射把这个形状认成一格 `map-has` ——
-- 那是**一处窥孔**，也记在账上。四门语言四种"问在不在"的写法，落的是同一格节点。

local m = {}
m["a"] = 1
m["b"] = 3
print(m["a"])
print(m["b"])
m["c"] = 4
print(m["c"])
if m["a"] ~= nil then
  print("yes")
end
