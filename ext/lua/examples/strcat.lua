-- ext/lua/examples/strcat.lua —— **串接**那一格的例子（第十三个例子家族）
--
-- 期望输出（家族里所有语言、所有后端逐行相同）：
--   ab
--   hi there
--
-- 四门语言四种写法：lua 的 `..`、nim 的 `&`、go 与 V 的 `+` —— 落到的是**同一格内建**
-- （`prim concat` / 落在串上的 `prim +`，不是新节点）。
-- 这一格在 wat 那条腿上是"新分配一块 + 两段字节拷过去"（`$__str_cat`），
-- 所以它同时钉住了字符串在线性内存里的那份布局（前 8 字节长度、正文从 +8 起）。

print("a" .. "b")
local s = "hi"
print(s .. " " .. "there")
