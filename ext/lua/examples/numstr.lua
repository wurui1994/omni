-- ext/lua/examples/numstr.lua —— **数 -> 串**（第十四个例子家族）
--
-- 期望输出（家族里所有语言、所有后端逐行相同）：
--   n=7
--   i=42
--
-- lua 的 `..` 混着数用是**语言自己的隐式转换**（`"n=" .. 7`）；nim 那份写成显式的 `$7`
-- （落 `conv` 那一格，目标是 `str`）。两种写法在图上不是同一格 —— 一格是内建 `concat`
-- 把数当串接，一格是 `conv` —— 但**印出来必须一样**，这就是这一族要钉的东西。
--
-- wat 那条腿上这一格是"造串"那台机器（`$__str_join` 里那圈数位循环）第二次用上：
-- 第一次是印一格多值。同一份代码两处用，不是抄两遍。

print("n=" .. 7)
local i = 42
print("i=" .. i)
