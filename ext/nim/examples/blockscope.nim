## ext/nim/examples/blockscope.nim —— **一段带自己作用域的语句**（`block:` -> region）
##
## 期望输出逐行相同：5 / 1。
##
## 单开一族的理由是账上算出来的：`region` 那格规格里十门都有，可矩阵只量到九门 ——
## 缺的正是 nim（它的例子里 region 全是**函数与 `defer:` 顺带带来的**，没有一处显式块）。
##
## 而这一份压的不只是"有没有这一格"，还有**它到底管不管用**：里外两个 `x` 同名，
## 块里印 5、块外印 1 —— 那两行就是"region 真的开了一层作用域"的判据。

var x = 1
block:
  var x = 5
  echo x
echo x
